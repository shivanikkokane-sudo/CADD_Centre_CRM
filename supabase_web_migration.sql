-- Run once in the Supabase SQL editor before starting the web CRM.
-- Existing desktop data is preserved.

create table if not exists public.crm_users (
    id bigint generated by default as identity primary key,
    full_name text not null,
    username text not null unique,
    password_hash text not null,
    role text not null default 'counsellor' check (role in ('admin', 'counsellor')),
    centre text not null default 'Dadar',
    is_active boolean not null default true,
    created_at timestamptz not null default now()
);

alter table public.enquiries add column if not exists decision_maker text default 'Not Specified';
alter table public.enquiries add column if not exists budget_range text default 'Not Discussed';
alter table public.enquiries add column if not exists planning_to_start text default 'Not Specified';
alter table public.enquiries add column if not exists demo_attended boolean default false;
alter table public.enquiries add column if not exists course_fee numeric(12,2) default 0;
alter table public.enquiries add column if not exists assigned_user_id bigint references public.crm_users(id);
alter table public.enquiries add column if not exists created_by bigint references public.crm_users(id);
alter table public.enquiries add column if not exists updated_by bigint references public.crm_users(id);
alter table public.enquiries add column if not exists joined_by bigint references public.crm_users(id);
alter table public.enquiries add column if not exists joined_at timestamptz;
alter table public.followup_logs add column if not exists created_by bigint references public.crm_users(id);

update public.enquiries set "Nearest_CADD_Centre" = 'Dadar'
where "Nearest_CADD_Centre" is null or trim("Nearest_CADD_Centre") in ('', 'NAN');

create index if not exists enquiries_assigned_user_idx on public.enquiries(assigned_user_id);
create index if not exists enquiries_status_idx on public.enquiries(status);
create index if not exists enquiries_next_followup_idx on public.enquiries(next_followup_datetime);

-- Stable contract for the future student-attendance application. Trainers should
-- receive SELECT access to this view, not to the complete enquiries table.
create or replace view public.joined_students as
select
    id as crm_enquiry_id,
    student_name,
    phone,
    email,
    course_interest as course_name,
    course_fee,
    "Nearest_CADD_Centre" as centre,
    joined_at,
    joined_by,
    true as is_active
from public.enquiries
where status = 'Joined';

